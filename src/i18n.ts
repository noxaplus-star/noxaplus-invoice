export function formatNumber(value: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === 'fa' ? 'fa-IR' : 'en-US', { maximumFractionDigits: 0 }).format(value);
}

export function currencyLabel(currency: Currency, lang: Lang): string {
  const labels: Record<Currency, [string, string]> = {
    IRT: ['تومان', 'Toman'],
    IRR: ['ریال', 'Rial'],
    USD: ['دلار', 'USD'],
    EUR: ['یورو', 'EUR'],
    AED: ['درهم', 'AED'],
  };
  return labels[currency][lang === 'fa' ? 0 : 1];
}
